// Generates the Vietnamese copy of the giỗ reminder (N1) for the server (server/digest-vi.js) and the app
// (web/js/digest-vi.js) from one JSON file. Usage: node scripts/gen-digest-vi.js <copy.json>
// The JSON keys are the only source; edit the JSON and run this again. The output is NFC and says so in its header.
'use strict';
const fs = require('fs');
const path = require('path');

const src = process.argv[2];
if (!src) { console.error('usage: node scripts/gen-digest-vi.js <copy.json>'); process.exit(2); }
const copy = JSON.parse(fs.readFileSync(src, 'utf8'));
for (const [k, v] of Object.entries(copy)) {
  if (typeof v !== 'string' || v.normalize('NFC') !== v) throw new Error(`${k}: text must be a string in NFC`);
}
const body = JSON.stringify(copy, null, 2);
const head = '// Generated by server/scripts/gen-digest-vi.js from the copy JSON. Do not edit by hand (NFC text).\n';
const serverOut = path.join(__dirname, '..', 'digest-vi.js');
const webOut = path.join(__dirname, '..', '..', 'web', 'js', 'digest-vi.js');
fs.writeFileSync(serverOut, `${head}'use strict';\nmodule.exports = ${body};\n`);
fs.writeFileSync(webOut, `${head}export default ${body};\n`);
console.log('wrote', serverOut, webOut);
