'use strict';
// Shared by the browser tests that run web/ against a mocked API (no database): the playwright and Chrome lookup, the
// skip reason, a launch helper and a static server for web/. A test file skips with the reason when one is missing.
const fs = require('fs');
const http = require('http');
const path = require('path');

let chromium = null;
try { ({ chromium } = require('playwright')); } catch {}
const CHROME = process.env.GP_E2E_CHROME || '/usr/bin/google-chrome';
const skip = !chromium ? 'playwright not installed (NODE_PATH)' : !fs.existsSync(CHROME) ? 'no Chrome at GP_E2E_CHROME' : false;
const WEB = path.join(__dirname, '..', '..', 'web');
const SHOTS = process.env.GP_SHOT_DIR || '';
const launch = () => chromium.launch({ executablePath: CHROME, headless: true, args: ['--no-sandbox'] });

// Serves web/ on a free port: resolves { base, srv }. The caller closes srv in test.after.
async function startWeb() {
  const srv = http.createServer((req, res) => {
    const u = new URL(req.url, 'http://x'); const pn = u.pathname === '/' ? '/index.html' : u.pathname === '/book' ? '/book.html' : u.pathname; const f = path.join(WEB, pn);
    if (!f.startsWith(WEB) || !fs.existsSync(f) || fs.statSync(f).isDirectory()) { res.writeHead(404); return res.end(); }
    const type = f.endsWith('.js') ? 'text/javascript' : f.endsWith('.css') ? 'text/css' : f.endsWith('.html') ? 'text/html' : f.endsWith('.svg') ? 'image/svg+xml' : 'application/octet-stream';
    res.writeHead(200, { 'content-type': type }); fs.createReadStream(f).pipe(res);
  });
  await new Promise((r) => srv.listen(0, '127.0.0.1', r));
  return { base: `http://127.0.0.1:${srv.address().port}`, srv };
}

module.exports = { skip, launch, startWeb, WEB, SHOTS, CHROME, chromium };
